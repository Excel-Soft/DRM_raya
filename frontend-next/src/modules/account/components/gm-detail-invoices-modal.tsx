"use client";

import type { ReactNode } from "react";
import { useQuery } from "@tanstack/react-query";
import { apiRequest } from "@/lib/query/query-client";
import { Badge } from "@/components/ui/badge";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/ui/legacy/dialog";
import { Button } from "@/components/ui/button";
import { FileText, HandCoins, ClipboardList, ImageIcon, Loader2 } from "lucide-react";
import { format } from "date-fns";
import { cn } from "@/lib/utils/cn";
import {
  accountPanelClass,
  accountTableWrapClass,
  accountTableClass,
  accountTableHeadRowClass,
  accountTableHeadCellClass,
  accountTableBodyRowClass,
} from "@/modules/account/account-ui";

interface GmInvoiceDetail {
  gm: {
    id: string;
    gmType: string;
    companyName: string;
    salesPersonName: string | null;
    packageType: string;
    status: string;
    amountUsd: string;
    customerDollar: string | null;
    createdAt: string | null;
    drmId: string | null;
    memberId: string | null;
    orderId: string | null;
    entryType: string | null;
    packagePriceUsd: string | null;
    alibabaDiscountUsd: string | null;
    extraDiscountUsd: string | null;
    extraDiscountPkr: string | null;
    dollarRate: string | null;
    amountPkr: string | null;
    paymentStatus: string | null;
    notes: string | null;
    dropout: string | null;
    extension: string | null;
    installments: string | null;
    paymentProofUrl: string | null;
    addedByName: string | null;
  };
  invoices: Array<{
    id: string;
    invoiceType: string | null;
    status: string;
    amount: string;
    currency: string;
    autoGenerated: boolean;
    hodApprovedBy: string | null;
    hodApprovedAt: string | null;
    accountsApprovedBy: string | null;
    accountsApprovedAt: string | null;
    rejectedBy: string | null;
    rejectedAt: string | null;
    rejectionReason: string | null;
    paidAmount: string | null;
    paidDate: string | null;
    paymentMethod: string | null;
    receiptReference: string | null;
    projectName: string | null;
    createdAt: string | null;
    projects: Array<{ id: string; name: string; status: string; departmentType: string | null }>;
  }>;
  partialReceipts: Array<{
    id: string;
    amountUsd: string;
    amountPkr: string | null;
    receiptDate: string | null;
    method: string | null;
    reference: string | null;
  }>;
  loanTerms: {
    loanAmountUsd: string | null;
    companyCopayUsd: string | null;
    agreedReturnDate: string | null;
    adminApprovalStatus: string | null;
    adminApprovedAt: string | null;
    returnStatus: string | null;
    returnedAt: string | null;
    overdue: boolean;
  } | null;
  summary: {
    invoiceCount: number;
    paymentConfirmationStatus: string;
    partialReceivedTotal: string | null;
    partialPendingTotal: string | null;
  };
}

function money(value: string | number | null | undefined): string {
  const n = Number(value ?? 0);
  if (Number.isNaN(n)) return "$0";
  return `$${n.toLocaleString(undefined, { maximumFractionDigits: 2 })}`;
}

function fmtDate(value: string | null | undefined): string {
  if (!value) return "—";
  const d = new Date(value);
  return Number.isNaN(d.getTime()) ? "—" : format(d, "dd MMM yyyy");
}

function pkr(value: string | number | null | undefined): string {
  const n = Number(value ?? 0);
  if (Number.isNaN(n) || n === 0) return "—";
  return `₨${n.toLocaleString(undefined, { maximumFractionDigits: 0 })}`;
}

function invoiceStatusBadge(status: string): "brand" | "success" | "warning" | "neutral" {
  const s = status.toLowerCase();
  if (s.includes("approved") || s.includes("paid")) return "success";
  if (s.includes("pending") || s.includes("hod")) return "warning";
  if (s.includes("reject")) return "neutral";
  return "brand";
}

function DetailField({ label, value }: { label: string; value: ReactNode }) {
  return (
    <div className="min-w-0">
      <p className="text-[11px] font-semibold uppercase tracking-wide text-zinc-500 dark:text-zinc-400">{label}</p>
      <p className="mt-0.5 text-sm font-medium text-zinc-900 dark:text-zinc-100">{value ?? "—"}</p>
    </div>
  );
}

function SectionPanel({
  title,
  description,
  icon,
  children,
  className,
}: {
  title: string;
  description?: string;
  icon?: ReactNode;
  children: ReactNode;
  className?: string;
}) {
  return (
    <div className={cn(accountPanelClass, "overflow-hidden", className)}>
      <div className="border-b border-zinc-200 px-4 py-3 dark:border-zinc-800">
        <div className="flex items-start gap-2">
          {icon ? <span className="mt-0.5 text-emerald-600">{icon}</span> : null}
          <div>
            <h3 className="text-sm font-semibold text-zinc-900 dark:text-zinc-100">{title}</h3>
            {description ? <p className="text-xs text-zinc-500 dark:text-zinc-400">{description}</p> : null}
          </div>
        </div>
      </div>
      <div className="p-4">{children}</div>
    </div>
  );
}

const detailDialogClass =
  "flex max-h-[90vh] w-full max-w-4xl flex-col gap-0 overflow-hidden border-zinc-200 bg-zinc-50 p-0 dark:border-zinc-800 dark:bg-zinc-950 sm:rounded-2xl";

export function GmDetailInvoicesModal({ gmId, onClose }: { gmId: string | null; onClose: () => void }) {
  const detailQuery = useQuery<GmInvoiceDetail>({
    queryKey: ["accounts-gm-invoice-detail", gmId],
    enabled: !!gmId,
    queryFn: async () => {
      const res = await apiRequest("GET", `/api/account/gm-entries/${gmId}/invoices`);
      if (!res.ok) throw new Error("Failed to load GM invoices");
      const body = await res.json();
      return body.data as GmInvoiceDetail;
    },
  });

  const gm = detailQuery.data?.gm;

  return (
    <Dialog open={!!gmId} onOpenChange={(open) => !open && onClose()}>
      <DialogContent className={detailDialogClass}>
        <DialogHeader className="shrink-0 border-b border-zinc-200 bg-white px-6 py-4 dark:border-zinc-800 dark:bg-zinc-900">
          <p className="text-[11px] font-bold uppercase tracking-wide text-emerald-700 dark:text-emerald-400">
            Account · GM detail
          </p>
          <DialogTitle className="flex items-center gap-2 text-left text-lg font-semibold text-zinc-900 dark:text-zinc-100">
            <FileText className="h-5 w-5 text-emerald-600" />
            Linked invoices &amp; receipts
          </DialogTitle>
          <DialogDescription className="text-left text-sm text-zinc-600 dark:text-zinc-400">
            {gm ? (
              <>
                <span className="font-medium text-zinc-800 dark:text-zinc-200">{gm.companyName}</span>
                <span className="mx-1.5 text-zinc-300">·</span>
                {gm.gmType}
                <span className="mx-1.5 text-zinc-300">·</span>
                <Badge variant="warning" className="align-middle normal-case">
                  {gm.status}
                </Badge>
              </>
            ) : (
              "Loading GM details…"
            )}
          </DialogDescription>
        </DialogHeader>

        <div className="min-h-0 flex-1 overflow-y-auto px-6 py-4">
          {detailQuery.isLoading && (
            <div className="flex items-center justify-center gap-2 py-16 text-sm text-zinc-500">
              <Loader2 className="h-5 w-5 animate-spin text-emerald-600" />
              Loading…
            </div>
          )}
          {detailQuery.isError && (
            <div className="rounded-xl border border-red-200 bg-red-50 px-4 py-8 text-center text-sm text-red-700 dark:border-red-900 dark:bg-red-950/40 dark:text-red-300">
              Failed to load GM details.
            </div>
          )}

          {detailQuery.data && (
            <div className="space-y-4">
              <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
                {[
                  { label: "Amount", value: money(detailQuery.data.gm.amountUsd) },
                  {
                    label: "Customer $",
                    value: detailQuery.data.gm.customerDollar ? money(detailQuery.data.gm.customerDollar) : "—",
                  },
                  { label: "Sales", value: detailQuery.data.gm.salesPersonName || "—" },
                  { label: "Created", value: fmtDate(detailQuery.data.gm.createdAt) },
                ].map((item) => (
                  <div key={item.label} className={cn(accountPanelClass, "px-4 py-3")}>
                    <p className="text-[11px] font-bold uppercase tracking-wide text-zinc-500">{item.label}</p>
                    <p className="mt-1 text-base font-semibold tabular-nums text-zinc-900 dark:text-zinc-100">
                      {item.value}
                    </p>
                  </div>
                ))}
              </div>

              {detailQuery.data.loanTerms && (
                <SectionPanel
                  title="Loan terms"
                  icon={<HandCoins className="h-4 w-4" />}
                  description={
                    detailQuery.data.loanTerms.overdue ? "This loan is overdue — review return status." : undefined
                  }
                  className={detailQuery.data.loanTerms.overdue ? "ring-1 ring-amber-200 dark:ring-amber-900" : undefined}
                >
                  <div className="mb-3 flex flex-wrap gap-2">
                    {detailQuery.data.loanTerms.overdue && <Badge variant="warning">Overdue</Badge>}
                  </div>
                  <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
                    <DetailField label="Loan amount" value={money(detailQuery.data.loanTerms.loanAmountUsd)} />
                    <DetailField label="Return by" value={fmtDate(detailQuery.data.loanTerms.agreedReturnDate)} />
                    <DetailField label="Admin approval" value={detailQuery.data.loanTerms.adminApprovalStatus} />
                    <DetailField label="Return status" value={detailQuery.data.loanTerms.returnStatus} />
                  </div>
                </SectionPanel>
              )}

              {detailQuery.data.partialReceipts.length > 0 && (
                <SectionPanel
                  title="Partial receipts"
                  description={
                    detailQuery.data.summary.partialPendingTotal != null
                      ? `Received ${money(detailQuery.data.summary.partialReceivedTotal)} · Pending ${money(detailQuery.data.summary.partialPendingTotal)}`
                      : undefined
                  }
                >
                  <div className={accountTableWrapClass}>
                    <table className={accountTableClass}>
                      <thead>
                        <tr className={accountTableHeadRowClass}>
                          {["Date", "Amount", "Method", "Reference"].map((h) => (
                            <th
                              key={h}
                              className={cn(
                                accountTableHeadCellClass,
                                h === "Amount" && "text-right",
                              )}
                            >
                              {h}
                            </th>
                          ))}
                        </tr>
                      </thead>
                      <tbody>
                        {detailQuery.data.partialReceipts.map((r) => (
                          <tr key={r.id} className={accountTableBodyRowClass}>
                            <td className="px-3 py-2">{fmtDate(r.receiptDate)}</td>
                            <td className="px-3 py-2 text-right tabular-nums font-medium">{money(r.amountUsd)}</td>
                            <td className="px-3 py-2">{r.method || "—"}</td>
                            <td className="px-3 py-2 text-zinc-600 dark:text-zinc-400">{r.reference || "—"}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </SectionPanel>
              )}

              <SectionPanel
                title={`Linked invoices (${detailQuery.data.summary.invoiceCount})`}
                description="Approval trail and linked projects."
              >
                {detailQuery.data.invoices.length === 0 ? (
                  <p className="py-6 text-center text-sm text-zinc-500">No invoices linked to this GM.</p>
                ) : (
                  <div className={accountTableWrapClass}>
                    <table className={cn(accountTableClass, "whitespace-nowrap")}>
                      <thead>
                        <tr className={accountTableHeadRowClass}>
                          {["Type", "Amount", "Status", "HOD", "Accounts", "Project"].map((h) => (
                            <th
                              key={h}
                              className={cn(accountTableHeadCellClass, h === "Amount" && "text-right")}
                            >
                              {h}
                            </th>
                          ))}
                        </tr>
                      </thead>
                      <tbody>
                        {detailQuery.data.invoices.map((inv) => (
                          <tr key={inv.id} className={accountTableBodyRowClass}>
                            <td className="px-3 py-2">
                              <span className="font-medium">{inv.invoiceType || "—"}</span>
                              <p className="text-[10px] uppercase tracking-wide text-zinc-500">
                                {inv.autoGenerated ? "Auto" : "Manual"}
                              </p>
                            </td>
                            <td className="px-3 py-2 text-right tabular-nums">{money(inv.amount)}</td>
                            <td className="px-3 py-2">
                              <Badge variant={invoiceStatusBadge(inv.status)} className="normal-case">
                                {inv.status.replace(/_/g, " ")}
                              </Badge>
                            </td>
                            <td className="px-3 py-2 text-xs text-zinc-600 dark:text-zinc-400">
                              {inv.hodApprovedAt ? `✓ ${fmtDate(inv.hodApprovedAt)}` : "—"}
                            </td>
                            <td className="px-3 py-2 text-xs text-zinc-600 dark:text-zinc-400">
                              {inv.accountsApprovedAt ? `✓ ${fmtDate(inv.accountsApprovedAt)}` : "—"}
                            </td>
                            <td className="max-w-[180px] truncate px-3 py-2 text-xs text-zinc-700 dark:text-zinc-300">
                              {inv.projects.length > 0
                                ? inv.projects.map((p) => `${p.name} (${p.status})`).join(", ")
                                : inv.projectName || "—"}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}
              </SectionPanel>

              <SectionPanel
                title="GM entry details"
                icon={<ClipboardList className="h-4 w-4" />}
                description="Original submission from Create GM."
              >
                <div className="space-y-5">
                  <div>
                    <p className="mb-2 text-[11px] font-bold uppercase tracking-wide text-zinc-500">Identifiers</p>
                    <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
                      <DetailField label="DRM ID" value={detailQuery.data.gm.drmId} />
                      <DetailField label="Member ID" value={detailQuery.data.gm.memberId} />
                      <DetailField label="Order ID" value={detailQuery.data.gm.orderId} />
                      <DetailField label="Type" value={detailQuery.data.gm.entryType} />
                    </div>
                  </div>

                  <div>
                    <p className="mb-2 text-[11px] font-bold uppercase tracking-wide text-zinc-500">Package &amp; pricing</p>
                    <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
                      <DetailField label="Package" value={detailQuery.data.gm.packageType || "—"} />
                      <DetailField label="Package price" value={money(detailQuery.data.gm.packagePriceUsd)} />
                      <DetailField label="AB discount" value={money(detailQuery.data.gm.alibabaDiscountUsd)} />
                      <DetailField label="Dollar rate" value={detailQuery.data.gm.dollarRate || "—"} />
                      <DetailField label="Extra $ discount" value={money(detailQuery.data.gm.extraDiscountUsd)} />
                      <DetailField label="Extra PKR discount" value={pkr(detailQuery.data.gm.extraDiscountPkr)} />
                      <DetailField label="PKR amount" value={pkr(detailQuery.data.gm.amountPkr)} />
                      <DetailField label="Payment status" value={detailQuery.data.gm.paymentStatus} />
                    </div>
                  </div>

                  <div>
                    <p className="mb-2 text-[11px] font-bold uppercase tracking-wide text-zinc-500">Other</p>
                    <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
                      <DetailField label="Added by" value={detailQuery.data.gm.addedByName} />
                      <DetailField label="Dropout" value={detailQuery.data.gm.dropout} />
                      <DetailField label="Extension" value={detailQuery.data.gm.extension} />
                      <DetailField
                        label="Payment screenshot"
                        value={
                          detailQuery.data.gm.paymentProofUrl ? (
                            <a
                              href={detailQuery.data.gm.paymentProofUrl}
                              target="_blank"
                              rel="noopener noreferrer"
                              className="inline-flex items-center gap-1 font-medium text-emerald-700 hover:underline dark:text-emerald-400"
                            >
                              <ImageIcon className="h-3.5 w-3.5" /> View
                            </a>
                          ) : (
                            "—"
                          )
                        }
                      />
                    </div>
                  </div>

                  {detailQuery.data.gm.notes && (
                    <div>
                      <p className="mb-2 text-[11px] font-bold uppercase tracking-wide text-zinc-500">Notes</p>
                      <p className="rounded-lg border border-zinc-200 bg-white p-3 text-sm whitespace-pre-wrap text-zinc-800 dark:border-zinc-700 dark:bg-zinc-900 dark:text-zinc-200">
                        {detailQuery.data.gm.notes}
                      </p>
                    </div>
                  )}
                </div>
              </SectionPanel>
            </div>
          )}
        </div>

        <DialogFooter className="shrink-0 border-t border-zinc-200 bg-white px-6 py-3 dark:border-zinc-800 dark:bg-zinc-900">
          <Button variant="secondary" size="sm" onClick={onClose}>
            Close
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
